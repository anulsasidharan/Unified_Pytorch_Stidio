    _validate_distribution()
    total = 0
    for topic_slug in ["functional", "comprehensions", "type-hints", "testing", "stdlib"]:
        seeded = await seed_questions_for_topic(
            topic_slug,
            QUESTIONS_BY_TOPIC[topic_slug],
            MODULE_LABELS[topic_slug],
        )
        total += seeded
    print(f"Seeded {total} questions across modules 16-20")


