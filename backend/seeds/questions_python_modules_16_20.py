def _validate_distribution() -> None:
    for topic_slug, expected in EXPECTED_COUNTS.items():
        questions = QUESTIONS_BY_TOPIC[topic_slug]
        counter = Counter(q["difficulty"] for q in questions)
        if dict(counter) != expected:
            raise ValueError(
                f"Distribution mismatch for {topic_slug}: got {dict(counter)}, expected {expected}"
            )
        if any(not q["slug"].startswith("py-") for q in questions):
            raise ValueError(f"All slugs for {topic_slug} must start with 'py-'")


