def _q(
    *,
    title: str,
    slug: str,
    difficulty: str,
    task: str,
    starter_code: str,
    solution_code: str,
    expected_output: str,
    tags: list[str],
    question_type: str = "code_completion",
    xp_reward: int | None = None,
    time_estimate_mins: int | None = None,
) -> dict:
    xp = xp_reward or {"basic": 8, "intermediate": 18, "advanced": 30}[difficulty]
    mins = time_estimate_mins or {"basic": 4, "intermediate": 8, "advanced": 12}[difficulty]
    return {
        "title": title,
        "slug": slug,
        "difficulty": difficulty,
        "question_type": question_type,
        "problem_statement": (
            f"## {title}\n\n"
            f"{task}\n\n"
            f"**Expected output:**\n```\n{expected_output}\n```\n"
        ),
        "starter_code": starter_code,
        "expected_output": expected_output,
        "tags": tags,
        "xp_reward": xp,
        "time_estimate_mins": mins,
        "solutions": [
            {
                "title": "Solution",
                "code": solution_code,
                "explanation": "",
                "is_optimal": True,
            }
        ],
    }


